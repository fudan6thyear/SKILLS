#!/usr/bin/env bash
# Install mid-huge-dev into every agent tool on this machine.
#
# Idempotent. Never overwrites a file it did not create — anything unexpected is
# reported and skipped, never clobbered. Run with --check to inspect first.
#
#   bash scripts/install.sh            install
#   bash scripts/install.sh --check    report only, write nothing
#
# Layout produced:
#   Claude Code   ~/.claude/skills/mid-huge-dev/            (this repo, native)
#                 ~/.claude/agents/*.md                     (native, untouched)
#   opencode      ~/.config/opencode/agent/<role>-agent.md  generated wrappers
#                 (skills: opencode already scans ~/.claude/skills — no install)
#   Codex         ~/.codex/skills/mid-huge-dev              symlink -> this repo
#   Any tool      ~/.agents/skills/mid-huge-dev             symlink -> this repo

set -euo pipefail

CHECK_ONLY=0
[ "${1:-}" = "--check" ] && CHECK_ONLY=1

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROLES_DIR="$SKILL_DIR/references/roles"

CLAUDE_SKILLS="$HOME/.claude/skills"
CLAUDE_AGENTS="$HOME/.claude/agents"
OPENCODE_AGENTS="$HOME/.config/opencode/agent"
CODEX_SKILLS="$HOME/.codex/skills"
AGENTS_SKILLS="$HOME/.agents/skills"

created=(); present=(); skipped=(); warned=()

say() { printf '%s\n' "$*"; }

# --- helpers ---------------------------------------------------------------

link_skill() {
  # $1 = target dir containing <name>; links <target>/mid-huge-dev -> SKILL_DIR
  local target="$1" dest
  dest="$target/mid-huge-dev"
  if [ -L "$dest" ]; then
    if [ "$(readlink "$dest")" = "$SKILL_DIR" ]; then present+=("$dest"); return 0; fi
    warned+=("$dest 已存在且指向别处（$(readlink "$dest")），未改动")
    return 1
  fi
  if [ -e "$dest" ]; then
    warned+=("$dest 已存在且不是符号链接，未改动")
    return 1
  fi
  if [ "$CHECK_ONLY" = "1" ]; then created+=("$dest (would create)"); return 0; fi
  mkdir -p "$target"
  ln -s "$SKILL_DIR" "$dest"
  created+=("$dest")
}

# --- 0. sanity -------------------------------------------------------------

say "mid-huge-dev 安装程序"
say "源目录: $SKILL_DIR"
say ""

if [ ! -f "$SKILL_DIR/SKILL.md" ]; then
  say "✗ 找不到 SKILL.md，源目录不对"; exit 1
fi
if [ ! -d "$ROLES_DIR" ] || [ -z "$(ls -A "$ROLES_DIR" 2>/dev/null)" ]; then
  say "⚠ references/roles/ 为空，先运行 scripts/sync-roles.sh 生成角色文件"
fi

# --- 1. Claude Code --------------------------------------------------------

say "[1/4] Claude Code"
if [ -d "$CLAUDE_SKILLS" ]; then
  # The skill is already here, but link it explicitly so the layout is obvious
  # and so a relocated copy still works.
  if [ "$(cd "$CLAUDE_SKILLS/mid-huge-dev" 2>/dev/null && pwd -P || true)" = "$SKILL_DIR" ]; then
    present+=("$CLAUDE_SKILLS/mid-huge-dev (原生位置)")
  fi
fi

missing_agents=0
for r in pm architect backend qa; do
  [ -f "$CLAUDE_AGENTS/$r-agent.md" ] || missing_agents=$((missing_agents + 1))
done
if [ "$missing_agents" -eq 0 ]; then
  present+=("$CLAUDE_AGENTS/{pm,architect,backend,qa}-agent.md (4 个原生代理)")
else
  warned+=("$CLAUDE_AGENTS 缺少 $missing_agents 个角色代理；Codex/opencode 会退回使用 references/roles/")
fi

# --- 2. opencode -----------------------------------------------------------

say "[2/4] opencode"
say "      技能：opencode 会直接扫描 ~/.claude/skills/，无需安装"
say "      代理：生成到 $OPENCODE_AGENTS"

# opencode agent frontmatter. `mode: subagent` keeps these out of the primary
# picker and reachable via task()/@ mention. No `model:` key — opencode falls
# back to the session model, which is safer than guessing a provider/model id.
write_opencode_agent() {
  local role="$1" cname="$2" desc="$3"
  local dest="$OPENCODE_AGENTS/${role}-agent.md"
  local is_ours=0
  [ -e "$dest" ] && grep -q 'generated by mid-huge-dev' "$dest" 2>/dev/null && is_ours=1

  if [ -e "$dest" ] && [ "$is_ours" = "0" ]; then
    warned+=("$dest 已存在且非本程序生成，未改动")
    return 0
  fi

  # Write to a buffer so an unchanged wrapper is left alone (no mtime churn).
  local body
  body="$(cat <<EOF
---
# generated by mid-huge-dev scripts/install.sh — 请勿手工编辑
# 修改角色内容请改 ~/.claude/agents/${role}-agent.md 后运行 scripts/sync-roles.sh
name: ${role}-agent
description: $desc
mode: subagent
tools:
  write: true
  edit: true
  bash: true
---

请先完整读取 \`$ROLES_DIR/$role.md\`，那是本角色的完整指令。
读取后严格按其中定义的核心职责、工作模式、禁止事项与回报格式执行。

## 在本工作流中的位置

- 你的输入是一张任务卡：\`docs/pm/tasks/\` 下以你的角色命名的那张
- 修改范围、契约约束、验收标准都在卡片里，**卡片即契约**
- 完成后按卡片末尾的「完工回报格式」提交结构化回报，缺任何一节都不算完工
- 发现卡片本身有问题（范围矛盾、契约冲突）→ 回报「受阻」，不要自行改设计

完整流程说明见技能 \`mid-huge-dev\`（$SKILL_DIR/SKILL.md）。
EOF
)"

  if [ -e "$dest" ] && [ "$(cat "$dest")" = "$body" ]; then
    present+=("$dest")
    return 0
  fi

  if [ "$CHECK_ONLY" = "1" ]; then
    if [ "$is_ours" = "1" ]; then created+=("$dest (would update)")
    else created+=("$dest (would create)"); fi
    return 0
  fi

  mkdir -p "$OPENCODE_AGENTS"
  printf '%s\n' "$body" > "$dest"
  if [ "$is_ours" = "1" ]; then present+=("$dest (已更新)")
  else created+=("$dest"); fi
}

write_opencode_agent pm        "项目经理" "项目管理 - 负责任务编排、状态维护、验收管理，不编写业务代码"
write_opencode_agent architect "架构师"   "架构师 - 负责技术方案设计、调研、接口定义、风险评估"
write_opencode_agent backend   "后端工程师" "后端工程师 - 负责服务端代码实现、单元测试、数据库操作"
write_opencode_agent qa        "QA 工程师" "QA 工程师 - 负责测试编写、功能验收、质量保证"

# --- 3. Codex --------------------------------------------------------------

say "[3/4] Codex"
link_skill "$CODEX_SKILLS"

# --- 4. portable ~/.agents ------------------------------------------------

say "[4/4] ~/.agents (通用位置，opencode 与 Codex 均会扫描)"
link_skill "$AGENTS_SKILLS"

# --- report ----------------------------------------------------------------

say ""
if [ ${#created[@]} -gt 0 ]; then
  say "已创建:"
  printf '  + %s\n' "${created[@]}"
fi
if [ ${#present[@]} -gt 0 ]; then
  say "已就位:"
  printf '  = %s\n' "${present[@]}"
fi
if [ ${#skipped[@]} -gt 0 ]; then
  say "已跳过:"
  printf '  - %s\n' "${skipped[@]}"
fi
if [ ${#warned[@]} -gt 0 ]; then
  say "需要留意:"
  printf '  ! %s\n' "${warned[@]}"
fi

say ""
if [ "$CHECK_ONLY" = "1" ]; then
  say "（--check 模式，未写入任何文件）"
else
  say "安装完成。以下工具需要重启才能加载新配置："
  say "  - opencode：配置与代理在启动时加载一次，不热重载"
  say "  - Codex：重启后重新扫描 ~/.codex/skills"
  say "  - Claude Code：新会话自动加载"
fi
say ""
say "验证："
say "  opencode 里   /mid-huge-dev status   或 @architect-agent"
say "  Codex 里      \$mid-huge-dev"
say "  Claude 里     /mid-huge-dev status"
